import { mkdirSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { getAllFlags } from './helpers.mjs';

const CELL_WIDTH = 30;
const CELL_HEIGHT = 24;
const COLUMNS = 20;

/** Strip the <svg> wrapper and return the drawing commands only. */
const innerSvg = (svg) => svg.replace(/^\s*<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\n\s*/g, '');

/** `.flag-poland` / `.flag-pl` — the selectors a flag answers to. */
const selectors = (flag) => {
  const names = [flag.slug];
  if (flag.iso && flag.iso.toLowerCase() !== flag.slug) names.push(flag.iso.toLowerCase());
  return names.map((n) => `.flag-${n}`).join(',\n');
};

const pct = (n) => `${Number((n * 100).toFixed(4))}%`;

/**
 * Pack every source flag into one SVG grid and emit a stylesheet that shows a
 * single cell via `background-position`. Positions are percentages, so one
 * class works at any element size; aliases share the cell of the flag they
 * point to instead of getting their own.
 */
export const buildSprite = ({ outDir, fileName = 'flags' }) => {
  const flags = getAllFlags();

  // Only flags with their own artwork take a cell; aliases reuse the target's.
  const cells = flags.filter((f) => !f.alias);
  const rows = Math.ceil(cells.length / COLUMNS);

  const cellOf = new Map();
  const groups = cells.map((flag, i) => {
    const col = i % COLUMNS;
    const row = Math.floor(i / COLUMNS);
    cellOf.set(flag.slug, { col, row });
    return `<g transform="translate(${col * CELL_WIDTH} ${row * CELL_HEIGHT})">${innerSvg(flag.content)}</g>`;
  });

  const sprite =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${COLUMNS * CELL_WIDTH} ${rows * CELL_HEIGHT}">` +
    groups.join('') +
    `</svg>\n`;

  const rules = flags.map((flag) => {
    const { col, row } = cellOf.get(flag.alias ?? flag.slug);
    const x = COLUMNS > 1 ? col / (COLUMNS - 1) : 0;
    const y = rows > 1 ? row / (rows - 1) : 0;
    return `${selectors(flag)} {\n  background-position: ${pct(x)} ${pct(y)};\n}`;
  });

  const css = `/* Generated by @tabler/flags — ${cells.length} flags in a ${COLUMNS}x${rows} grid */
.flag {
  display: inline-block;
  width: 1.25em;
  height: 1em;
  vertical-align: -0.125em;
  background-image: url("./${fileName}.svg");
  background-repeat: no-repeat;
  background-size: ${COLUMNS * 100}% ${rows * 100}%;
}

.flag-rounded {
  border-radius: 0.1667em;
  box-shadow: inset 0 0 0 1px rgba(0, 0, 0, 0.15);
}

${rules.join('\n\n')}
`;

  const map = Object.fromEntries(
    flags.map((flag) => {
      const { col, row } = cellOf.get(flag.alias ?? flag.slug);
      return [flag.slug, { x: col * CELL_WIDTH, y: row * CELL_HEIGHT, iso: flag.iso }];
    }),
  );

  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, `${fileName}.svg`), sprite, 'utf8');
  writeFileSync(resolve(outDir, `${fileName}.css`), css, 'utf8');
  writeFileSync(
    resolve(outDir, `${fileName}.json`),
    JSON.stringify({ cell: { width: CELL_WIDTH, height: CELL_HEIGHT }, columns: COLUMNS, rows, flags: map }, null, 2) + '\n',
    'utf8',
  );

  return { cells: cells.length, rows };
};
